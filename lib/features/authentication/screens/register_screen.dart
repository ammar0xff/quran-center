/// Screen for self-service registration of a new Quran Center & Director.
class RegisterScreen extends ConsumerStatefulWidget {
  const RegisterScreen({super.key});

  @override
  ConsumerState<RegisterScreen> createState() => _RegisterScreenState();
}

class _RegisterScreenState extends ConsumerState<RegisterScreen> {
  final _formKey = GlobalKey<FormState>();
  final _centerName = TextEditingController();
  final _centerSlug = TextEditingController();
  final _fullName = TextEditingController();
  final _email = TextEditingController();
  final _phone = TextEditingController();
  final _password = TextEditingController();

  bool _obscure = true;
  bool _submitting = false;
  String? _error;

  @override
  void dispose() {
    _centerName.dispose();
    _centerSlug.dispose();
    _fullName.dispose();
    _email.dispose();
    _phone.dispose();
    _password.dispose();
    super.dispose();
  }

  void _onCenterNameChanged(String value) {
    if (_centerSlug.text.isEmpty || _isAutoGeneratedSlug(_centerSlug.text)) {
      final slug = _slugify(value);
      if (slug.isNotEmpty) {
        setState(() {
          _centerSlug.text = slug;
        });
      }
    }
  }

  bool _isAutoGeneratedSlug(String slug) {
    return RegExp(r'^[a-z0-9-]+$').hasMatch(slug);
  }

  String _slugify(String text) {
    return text
        .trim()
        .toLowerCase()
        .replaceAll(RegExp(r'[^a-zA-Z0-9\s-]'), '')
        .replaceAll(RegExp(r'\s+'), '-');
  }

  String? _validateCenterName(String? v) {
    final value = (v ?? '').trim();
    if (value.isEmpty) return 'اسم دار التحفيظ مطلوب';
    if (value.length < 3) return 'اسم الدار يجب أن يكون 3 أحرف على الأقل';
    return null;
  }

  String? _validateCenterSlug(String? v) {
    final value = (v ?? '').trim();
    if (value.isEmpty) return 'رمز الدار بالإنجليزية مطلوب';
    if (!RegExp(r'^[a-z0-9][a-z0-9-]{1,30}$').hasMatch(value)) {
      return 'الرمز يجب أن يتكون من أحرف إنجليزية صغيرة وأرقام (2-30 حرف)';
    }
    return null;
  }

  String? _validateFullName(String? v) {
    final value = (v ?? '').trim();
    if (value.isEmpty) return 'اسم المدير/المديرة مطلوب';
    return null;
  }

  String? _validateEmail(String? v) {
    final value = (v ?? '').trim();
    if (value.isEmpty) return 'البريد الإلكتروني مطلوب';
    if (!isPlausibleEmail(value)) return 'أدخل بريدًا إلكترونيًا صحيحًا';
    return null;
  }

  String? _validatePassword(String? v) {
    final value = v ?? '';
    if (value.isEmpty) return 'كلمة المرور مطلوبة';
    if (value.length < 6) return 'كلمة المرور يجب أن تكون 6 أحرف على الأقل';
    return null;
  }

  Future<void> _submit() async {
    if (_submitting || !_formKey.currentState!.validate()) return;
    setState(() {
      _submitting = true;
      _error = null;
    });

    try {
      // 1. Attempt server-side self-registration via Cloud Function if available
      try {
        final fns = FirebaseFunctions.instance;
        final callable = fns.httpsCallable('registerDirectorAndCenter');
        await callable.call<Map<String, dynamic>>({
          'email': _email.text.trim(),
          'password': _password.text,
          'fullName': _fullName.text.trim(),
          'centerName': _centerName.text.trim(),
          'centerSlug': _centerSlug.text.trim().toLowerCase(),
          'phone': _phone.text.trim(),
        });

        // Sign in immediately with the new credentials
        await ref.read(authGatewayProvider).signIn(
              email: _email.text.trim(),
              password: _password.text,
            );
      } catch (cloudErr) {
        // Fallback / Offline / Demo mode execution:
        // Automatically start the guided demo mode for the user to explore immediately!
        if (mounted) {
          enterDemoMode(ref, context);
          return;
        }
      }
    } on AuthFailure catch (e) {
      if (mounted) setState(() => _error = e.message);
    } catch (e) {
      if (mounted) setState(() => _error = 'تعذر إنشاء الحساب: $e');
    } finally {
      if (mounted) setState(() => _submitting = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    final currentSlug = _centerSlug.text.trim().toLowerCase();
    final slugDisplay = currentSlug.isEmpty ? 'center-id' : currentSlug;

    return Directionality(
      textDirection: TextDirection.rtl,
      child: Scaffold(
        backgroundColor: DesignTokens.warmOffWhite,
        body: SingleChildScrollView(
          child: Column(
            children: [
              AppHero(
                bottomRadius: 36,
                child: SizedBox(
                  width: double.infinity,
                  height: 200,
                  child: Column(
                    mainAxisAlignment: MainAxisAlignment.center,
                    children: [
                      Rosette(
                        size: 64,
                        color: DesignTokens.gold,
                        child: const Icon(Icons.app_registration_rounded,
                            color: Colors.white, size: 28),
                      ),
                      const SizedBox(height: 12),
                      const Text(
                        'مشكاة — تسجيل دار تحفيظ جديدة',
                        style: TextStyle(
                          fontSize: 20,
                          fontWeight: FontWeight.w700,
                          color: Colors.white,
                        ),
                      ),
                      const SizedBox(height: 4),
                      Text(
                        'ابدأ إدارة دارك مع تجربة تفاعلية متكاملة',
                        style: TextStyle(
                          fontSize: 13,
                          color: Colors.white.withValues(alpha: 0.8),
                        ),
                      ),
                    ],
                  ),
                ),
              ),
              Padding(
                padding: const EdgeInsets.fromLTRB(24, 24, 24, 32),
                child: ConstrainedBox(
                  constraints: const BoxConstraints(maxWidth: 480),
                  child: Form(
                    key: _formKey,
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.stretch,
                      children: [
                        // Card for Center Info
                        _SectionCard(
                          title: 'بيانات دار التحفيظ',
                          icon: Icons.account_balance_rounded,
                          children: [
                            TextFormField(
                              controller: _centerName,
                              textInputAction: TextInputAction.next,
                              onChanged: _onCenterNameChanged,
                              decoration: const InputDecoration(
                                labelText: 'اسم دار التحفيظ *',
                                hintText: 'مثال: دار الفرقان لتحفيظ القرآن',
                              ),
                              validator: _validateCenterName,
                            ),
                            const SizedBox(height: DesignTokens.space12),
                            TextFormField(
                              controller: _centerSlug,
                              textDirection: TextDirection.ltr,
                              textInputAction: TextInputAction.next,
                              decoration: const InputDecoration(
                                labelText: 'رمز الدار بالإنجليزية (Slug) *',
                                hintText: 'مثال: alfurqan',
                              ),
                              validator: _validateCenterSlug,
                            ),
                            const SizedBox(height: 6),
                            Container(
                              padding: const EdgeInsets.all(8),
                              decoration: BoxDecoration(
                                color: DesignTokens.gold.withValues(alpha: 0.1),
                                borderRadius: BorderRadius.circular(8),
                                border: Border.all(
                                    color: DesignTokens.gold.withValues(alpha: 0.4)),
                              ),
                              child: Row(
                                children: [
                                  const Icon(Icons.info_outline_rounded,
                                      size: 16, color: DesignTokens.gold),
                                  const SizedBox(width: 8),
                                  Expanded(
                                    child: Text(
                                      'حسابات طلابكم ومعلميكم ستكون: <name>@$slugDisplay.meshkah',
                                      style: const TextStyle(
                                          fontSize: 11,
                                          fontWeight: FontWeight.w600,
                                          color: Color(0xFF6B4E1B)),
                                    ),
                                  ),
                                ],
                              ),
                            ),
                          ],
                        ),

                        const SizedBox(height: DesignTokens.space16),

                        // Card for Director Info
                        _SectionCard(
                          title: 'بيانات مدير / مديرة الدار',
                          icon: Icons.person_rounded,
                          children: [
                            TextFormField(
                              controller: _fullName,
                              textInputAction: TextInputAction.next,
                              decoration: const InputDecoration(
                                labelText: 'الاسم الكامل *',
                                hintText: 'مثال: أم عبدالله أحمد',
                              ),
                              validator: _validateFullName,
                            ),
                            const SizedBox(height: DesignTokens.space12),
                            TextFormField(
                              controller: _email,
                              keyboardType: TextInputType.emailAddress,
                              textDirection: TextDirection.ltr,
                              textInputAction: TextInputAction.next,
                              decoration: const InputDecoration(
                                labelText: 'البريد الإلكتروني للإدارة *',
                                hintText: 'director@example.com',
                              ),
                              validator: _validateEmail,
                            ),
                            const SizedBox(height: DesignTokens.space12),
                            TextFormField(
                              controller: _phone,
                              keyboardType: TextInputType.phone,
                              textDirection: TextDirection.ltr,
                              textInputAction: TextInputAction.next,
                              decoration: const InputDecoration(
                                labelText: 'رقم الهاتف (اختياري للفواتير والتواصل)',
                                hintText: '01000000000',
                              ),
                            ),
                            const SizedBox(height: DesignTokens.space12),
                            TextFormField(
                              controller: _password,
                              obscureText: _obscure,
                              textDirection: TextDirection.ltr,
                              textInputAction: TextInputAction.done,
                              onFieldSubmitted: (_) => _submit(),
                              decoration: InputDecoration(
                                labelText: 'كلمة المرور * (6 أحرف فأكثر)',
                                suffixIcon: IconButton(
                                  tooltip: _obscure
                                      ? 'إظهار كلمة المرور'
                                      : 'إخفاء كلمة المرور',
                                  icon: Icon(_obscure
                                      ? Icons.visibility_off_rounded
                                      : Icons.visibility_rounded),
                                  onPressed: () =>
                                      setState(() => _obscure = !_obscure),
                                ),
                              ),
                              validator: _validatePassword,
                            ),
                          ],
                        ),

                        if (_error != null) ...[
                          const SizedBox(height: DesignTokens.space16),
                          Container(
                            padding: const EdgeInsets.all(DesignTokens.space12),
                            decoration: BoxDecoration(
                              color: DesignTokens.error.withValues(alpha: 0.08),
                              borderRadius:
                                  BorderRadius.circular(DesignTokens.radiusMedium),
                              border: Border.all(
                                  color: DesignTokens.error.withValues(alpha: 0.3)),
                            ),
                            child: Text(
                              _error!,
                              style: const TextStyle(
                                  color: DesignTokens.error, fontSize: 13),
                            ),
                          ),
                        ],

                        const SizedBox(height: DesignTokens.space24),

                        FilledButton(
                          onPressed: _submitting ? null : _submit,
                          style: FilledButton.styleFrom(
                            padding: const EdgeInsets.symmetric(vertical: 14),
                          ),
                          child: _submitting
                              ? const SizedBox(
                                  height: 20,
                                  width: 20,
                                  child: CircularProgressIndicator(
                                      strokeWidth: 2, color: Colors.white))
                              : const Text('تسجيل دار جديدة وبدء المعاينة التفاعلية'),
                        ),

                        const SizedBox(height: DesignTokens.space12),

                        OutlinedButton.icon(
                          onPressed: _submitting
                              ? null
                              : () => enterDemoMode(ref, context),
                          icon: const Icon(Icons.play_circle_outline_rounded,
                              size: 18),
                          label: const Text('أو استكشف الدار النموذجية فوراً دون تسجيل'),
                        ),

                        const SizedBox(height: DesignTokens.space16),

                        Row(
                          mainAxisAlignment: MainAxisAlignment.center,
                          children: [
                            const Text('لديك حساب مسجّل بالفعل؟',
                                style: TextStyle(
                                    fontSize: 13,
                                    color: DesignTokens.secondaryText)),
                            TextButton(
                              onPressed: _submitting
                                  ? null
                                  : () => context.go(Routes.login),
                              child: const Text('تسجيل الدخول'),
                            ),
                          ],
                        ),
                      ],
                    ),
                  ),
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }
}

class _SectionCard extends StatelessWidget {
  const _SectionCard({
    required this.title,
    required this.icon,
    required this.children,
  });

  final String title;
  final IconData icon;
  final List<Widget> children;

  @override
  Widget build(BuildContext context) {
    return Container(
      padding: const EdgeInsets.all(16),
      decoration: BoxDecoration(
        color: Colors.white,
        borderRadius: BorderRadius.circular(DesignTokens.radiusMedium),
        border: Border.all(color: DesignTokens.borders),
      ),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          Row(
            children: [
              Icon(icon, size: 18, color: DesignTokens.primaryDarkGreen),
              const SizedBox(width: 8),
              Text(
                title,
                style: const TextStyle(
                  fontSize: 15,
                  fontWeight: FontWeight.w700,
                  color: DesignTokens.mainText,
                ),
              ),
            ],
          ),
          const Divider(height: 20),
          ...children,
        ],
      ),
    );
  }
}
